// Normalises raw provider logos into uniform 96×96 PNG badges.
//   node scripts/build-provider-logos.mjs <raw-dir>
// Each <slug>.<png|jpg|webp|ico|svg> in raw-dir becomes public/providers/<slug>.png:
// the mark is fitted (contain) inside a white square with even padding. Images
// are rendered via <img> in headless Chromium, so no file content can execute.
import { chromium } from "@playwright/test";
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { extname, join, basename } from "node:path";

const SIZE = 96;
const PAD = Number(process.env.LOGO_PAD ?? 10); // px of breathing room inside the tile
const MIME = { ".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".webp": "image/webp", ".ico": "image/x-icon", ".svg": "image/svg+xml", ".gif": "image/gif" };

const rawDir = process.argv[2];
if (!rawDir) throw new Error("usage: node scripts/build-provider-logos.mjs <raw-dir>");
const outDir = new URL("../public/providers/", import.meta.url);
await mkdir(outDir, { recursive: true });

const files = (await readdir(rawDir)).filter((f) => MIME[extname(f).toLowerCase()]);
const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
const page = await browser.newPage({ viewport: { width: SIZE, height: SIZE }, deviceScaleFactor: 1 });
const done = [];
for (const f of files.sort()) {
  const slug = basename(f, extname(f)).toLowerCase();
  if (!/^[a-z0-9-]+$/.test(slug)) continue;
  const data = (await readFile(join(rawDir, f))).toString("base64");
  const src = `data:${MIME[extname(f).toLowerCase()]};base64,${data}`;
  await page.setContent(
    `<html><body style="margin:0;background:#fff;width:${SIZE}px;height:${SIZE}px;display:grid;place-items:center">
       <img id="i" src="${src}" style="max-width:${SIZE - 2 * PAD}px;max-height:${SIZE - 2 * PAD}px;width:auto;height:auto;object-fit:contain;image-rendering:auto"/>
     </body></html>`,
  );
  const ok = await page.evaluate(async () => {
    const img = document.getElementById("i");
    await img.decode().catch(() => undefined);
    // Upscale tiny favicons to fill the safe area.
    if (img.naturalWidth && img.naturalWidth < 80) {
      const s = Math.min(76 / img.naturalWidth, 76 / img.naturalHeight);
      img.style.width = `${img.naturalWidth * s}px`;
      img.style.height = `${img.naturalHeight * s}px`;
    }
    return img.naturalWidth > 0;
  });
  if (!ok) {
    console.warn("skip (not a decodable image):", f);
    continue;
  }
  await page.screenshot({ path: new URL(`${slug}.png`, outDir).pathname, clip: { x: 0, y: 0, width: SIZE, height: SIZE } });
  done.push(slug);
  console.log("wrote", `${slug}.png`);
}
await browser.close();

const all = new Set([...done, ...(await readdir(outDir)).filter((f) => f.endsWith(".png")).map((f) => f.slice(0, -4))]);
await writeFile(
  new URL("../src/providers.generated.ts", import.meta.url),
  `// Generated by scripts/build-provider-logos.mjs — slugs with a vetted logo in public/providers/.\nexport const PROVIDER_LOGOS: ReadonlySet<string> = new Set(${JSON.stringify([...all].sort())});\n`,
);
console.log(`${all.size} provider logos available`);
